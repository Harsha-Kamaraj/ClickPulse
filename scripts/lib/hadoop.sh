#!/usr/bin/env bash
# Shared Hadoop helpers (sourced by vm1/vm2/vm3/vm4 install scripts).
# Every VM uses the SAME core-site.xml / hdfs-site.xml -> one HDFS cluster
# whose NameNode + DataNode live on VM2 (cp-vm2).

# Write core-site.xml + hdfs-site.xml into the given directory.
#   render_hadoop_conf <dir>          Hadoop/Spark clients and servers (fs.defaultFS = HDFS on VM2)
#   render_hadoop_conf <dir> druid    for Druid's conf/_common: NO fs.defaultFS, because Druid's HDFS
#                                     extension then connects to it at startup and every Druid service
#                                     dies if HDFS is down. Ingestion uses full hdfs://cp-vm2:9000/ URIs.
render_hadoop_conf() {
  local dest="$1" flavour="${2:-}" default_fs=""
  mkdir -p "$dest"
  [[ "$flavour" == "druid" ]] || default_fs="  <property><name>fs.defaultFS</name><value>${HDFS_URI}</value></property>"
  cat > "$dest/core-site.xml" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by ClickPulse scripts/lib/hadoop.sh ${flavour:+(variant: $flavour)} -->
<configuration>
${default_fs}
  <property><name>hadoop.tmp.dir</name><value>${CP_DATA}/hadoop/tmp</value></property>
  <property><name>hadoop.http.staticuser.user</name><value>${VM2_USER}</value></property>
</configuration>
EOF
  cat > "$dest/hdfs-site.xml" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by ClickPulse scripts/lib/hadoop.sh - identical on all VMs -->
<configuration>
  <!-- single DataNode (VM2) -> replication 1 -->
  <property><name>dfs.replication</name><value>1</value></property>
  <property><name>dfs.namenode.name.dir</name><value>file://${CP_DATA}/hadoop/namenode</value></property>
  <property><name>dfs.datanode.data.dir</name><value>file://${CP_DATA}/hadoop/datanode</value></property>

  <!-- listen on every interface (incl. ZeroTier) -->
  <property><name>dfs.namenode.rpc-bind-host</name><value>0.0.0.0</value></property>
  <property><name>dfs.namenode.servicerpc-bind-host</name><value>0.0.0.0</value></property>
  <property><name>dfs.namenode.http-bind-host</name><value>0.0.0.0</value></property>

  <!-- DataNode advertises the cluster alias; clients resolve it to the ZeroTier IP -->
  <property><name>dfs.datanode.hostname</name><value>${VM2_HOST}</value></property>
  <property><name>dfs.client.use.datanode.hostname</name><value>true</value></property>
  <property><name>dfs.datanode.use.datanode.hostname</name><value>true</value></property>
  <property><name>dfs.namenode.datanode.registration.ip-hostname-check</name><value>false</value></property>

  <!-- 4 different Linux users write to the same dirs -->
  <property><name>dfs.permissions.enabled</name><value>false</value></property>
</configuration>
EOF
}

# Download + unpack Hadoop and write its config (client or server).
install_hadoop() {
  local tgz="$CP_DOWNLOADS/hadoop-${HADOOP_VERSION}.tar.gz"
  download "hadoop/common/hadoop-${HADOOP_VERSION}/hadoop-${HADOOP_VERSION}.tar.gz" "$tgz"
  install_tarball "$tgz" "$HADOOP_HOME"
  render_hadoop_conf "$HADOOP_CONF_DIR"
  mkdir -p "$CP_LOGS/hadoop" "$CP_RUN"
  # hadoop-env.sh: pin JAVA_HOME, logs and pids
  local envf="$HADOOP_CONF_DIR/hadoop-env.sh"
  sed -i '/# >>> ClickPulse/,/# <<< ClickPulse/d' "$envf"
  cat >> "$envf" <<EOF
# >>> ClickPulse >>>
export JAVA_HOME=${JAVA_HOME}
export HADOOP_LOG_DIR=${CP_LOGS}/hadoop
export HADOOP_PID_DIR=${CP_RUN}
export HADOOP_HEAPSIZE_MAX=1g
# <<< ClickPulse <<<
EOF
  ok "Hadoop ${HADOOP_VERSION} configured (fs.defaultFS=${HDFS_URI})"
}
