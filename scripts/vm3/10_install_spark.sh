#!/usr/bin/env bash
# =============================================================================
#  RUN ON: VM3  (Gagan R)  - once, after scripts/all/00_bootstrap_vm.sh
#
#  Installs:
#   * Apache Spark ${SPARK_VERSION} (standalone: master + worker + driver on VM3)
#   * Apache Iceberg Spark runtime jar (curated table format)
#   * Hadoop client config so Spark reads/writes the shared HDFS on VM2
# =============================================================================
source "$(dirname "$0")/../lib/common.sh"
source "$CP_ROOT/scripts/lib/hadoop.sh"
set -e  # stop at the first error
require_not_root
expect_vm 3

banner "VM3 install: Spark ${SPARK_VERSION} standalone + Iceberg ${ICEBERG_VERSION} + HDFS client"

step "Hadoop client (same core-site/hdfs-site as VM2)"
install_hadoop

step "Spark binaries"
TGZ="$CP_DOWNLOADS/spark-${SPARK_VERSION}-bin-hadoop3.tgz"
download "spark/spark-${SPARK_VERSION}/spark-${SPARK_VERSION}-bin-hadoop3.tgz" "$TGZ"
install_tarball "$TGZ" "$SPARK_HOME"

step "Iceberg runtime jar"
JAR="iceberg-spark-runtime-3.5_2.12-${ICEBERG_VERSION}.jar"
download_url "https://repo1.maven.org/maven2/org/apache/iceberg/iceberg-spark-runtime-3.5_2.12/${ICEBERG_VERSION}/${JAR}" \
  "$CP_DOWNLOADS/$JAR"
cp -f "$CP_DOWNLOADS/$JAR" "$SPARK_HOME/jars/"
ok "$JAR -> $SPARK_HOME/jars/"

step "Spark config"
mkdir -p "$CP_LOGS/spark" "$CP_RUN" "$CP_DATA/spark-work"
cat > "$SPARK_HOME/conf/spark-env.sh" <<EOF
# Generated by ClickPulse scripts/vm3/10_install_spark.sh
export JAVA_HOME=${JAVA_HOME}
export HADOOP_CONF_DIR=${HADOOP_CONF_DIR}
export SPARK_MASTER_HOST=${VM3_HOST}
export SPARK_LOCAL_IP=${VM3_IP}
export SPARK_WORKER_CORES=${SPARK_WORKER_CORES}
export SPARK_WORKER_MEMORY=${SPARK_WORKER_MEMORY}
export SPARK_WORKER_DIR=${CP_DATA}/spark-work
export SPARK_LOG_DIR=${CP_LOGS}/spark
export SPARK_PID_DIR=${CP_RUN}
export PYSPARK_PYTHON=python3
export PYSPARK_DRIVER_PYTHON=python3
EOF
cat > "$SPARK_HOME/conf/spark-defaults.conf" <<EOF
# Generated by ClickPulse - Iceberg catalog 'cp' stored on HDFS (VM2)
spark.master                              ${SPARK_MASTER_URL}
spark.sql.extensions                      org.apache.iceberg.spark.extensions.IcebergSparkSessionExtensions
spark.sql.catalog.cp                      org.apache.iceberg.spark.SparkCatalog
spark.sql.catalog.cp.type                 hadoop
spark.sql.catalog.cp.warehouse            ${ICEBERG_WAREHOUSE}
spark.sql.session.timeZone                UTC
spark.sql.shuffle.partitions              4
spark.driver.memory                       ${SPARK_DRIVER_MEMORY}
spark.executor.memory                     ${SPARK_EXECUTOR_MEMORY}
EOF
ok "spark-env.sh + spark-defaults.conf written"

banner "VM3 install done" "Next: scripts/vm3/11_start_spark.sh"
